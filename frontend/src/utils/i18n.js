export const getLang = () => localStorage.getItem('bhumi_lang') || 'hi';
export const setLang = (lang) => {
  localStorage.setItem('bhumi_lang', lang);
  window.dispatchEvent(new Event('langchange'));
};
export const t = (key) => {
  const lang = getLang();
  return translations[lang]?.[key] || translations['hi'][key] || key;
};
